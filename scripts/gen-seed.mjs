// Writes supabase/seed.sql (reference localities) and supabase/demo-backup.json (demo cases to restore
// into a real account) from the same seed module the fake data layer uses.
// Usage: node scripts/gen-seed.mjs
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { COMPLEXES, DISTRICTS, ESTABLISHMENTS, STATES, buildSeed } from "../src/lib/data/seed.ts";

// Deterministic UUID from a slug, so seed.sql and the demo backup agree.
function uuid(slug) {
  const h = createHash("md5").update("almirah:" + slug).digest("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
}
const q = (s) => `'${String(s).replaceAll("'", "''")}'`;

const rows = (table, cols, items) =>
  `insert into ${table} (${cols.join(", ")}) values\n` +
  items.map((r) => `  (${r.join(", ")})`).join(",\n") +
  "\non conflict (id) do nothing;\n";

const sql = [
  "-- Generated by scripts/gen-seed.mjs. Reference localities only; no user data.",
  rows("states", ["id", "name"], STATES.map((s) => [q(uuid(s.id)), q(s.name)])),
  rows("districts", ["id", "state_id", "name"], DISTRICTS.map((d) => [q(uuid(d.id)), q(uuid(d.parentId)), q(d.name)])),
  rows("court_complexes", ["id", "district_id", "name", "kind"], COMPLEXES.map((c) => [q(uuid(c.id)), q(uuid(c.parentId)), q(c.name), q(c.kind ?? "district")])),
  rows("court_establishments", ["id", "complex_id", "name"], ESTABLISHMENTS.map((e) => [q(uuid(e.id)), q(uuid(e.parentId)), q(e.name)])),
].join("\n");
writeFileSync("supabase/seed.sql", sql);

const today = new Date(Date.now() + 330 * 60_000).toISOString().slice(0, 10);
const cases = buildSeed(today).map((c) => ({
  ...c,
  establishmentId: c.establishmentId && uuid(c.establishmentId),
  stateId: undefined,
  districtId: undefined,
  complexId: undefined,
  orders: c.orders.map(({ orderNumber, orderDate }) => ({ orderNumber, orderDate })),
  source: "seed",
}));
writeFileSync(
  "supabase/demo-backup.json",
  JSON.stringify({ format: "almirah-backup", version: 1, exportedAt: new Date().toISOString(), cases }, null, 2),
);
console.log(`seed.sql: ${STATES.length + DISTRICTS.length + COMPLEXES.length + ESTABLISHMENTS.length} rows; demo-backup.json: ${cases.length} cases`);
